//-----------------------------------------------------------------------------------
bool FPKWareDecoder::Decompress(void)
{
	OutLen = MAX_OUT_SIZE;
	OutPos = 0;
	int ret = blast(inf, this, outf, this);
	if(ret == 0 && OutPos)
	{
		OutLen = OutPos;
		return true;
	}
	return false;
}
